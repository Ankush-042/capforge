require('dotenv').config();
/**
 * Write SEED-ACCOUNTS.md from the database.
 *
 * GENERATED, NOT TYPED. A credentials list maintained by hand goes stale the
 * first time anything is seeded, and a demo run from a stale list fails in
 * front of an audience. This reads the real accounts, so re-running it after
 * any seeding gives a file that is true by construction.
 *
 * Passwords are not read from anywhere — they cannot be, they are hashed.
 * The seeded ones share a known password and accounts created by hand are
 * listed without one.
 *
 * Usage: node scripts/write-credentials.js
 */
const fs = require('fs');
const path = require('path');
const pool = require('../backend/shared/db');

const SEED_PASSWORD = 'SeedPass123!';

(async () => {
  const founders = (await pool.query(
    `SELECT u.email, p.display_name, p.headline,
            s.name AS startup, s.domain, s.stage,
            (SELECT overall_score FROM readiness_assessments ra
             WHERE ra.startup_id = s.id ORDER BY ra.generated_at DESC LIMIT 1) AS readiness,
            (SELECT COUNT(*)::int FROM startup_team_members tm
             WHERE tm.startup_id = s.id AND tm.is_founder = false) AS team,
            (SELECT COUNT(*)::int FROM gaps g
             WHERE g.startup_id = s.id AND g.status NOT IN ('FILLED','DISMISSED')) AS open_roles
     FROM users u
     JOIN profiles p ON p.user_id = u.id
     LEFT JOIN startups s ON s.founder_id = u.id
     WHERE u.primary_role = 'FOUNDER'
     ORDER BY s.domain[1] NULLS LAST, s.name`
  )).rows;

  const contributors = (await pool.query(
    `SELECT u.email, p.display_name, p.headline, cp.preferred_domains
     FROM users u
     JOIN profiles p ON p.user_id = u.id
     LEFT JOIN contributor_profiles cp ON cp.profile_id = p.id
     WHERE u.primary_role = 'CONTRIBUTOR'
     ORDER BY u.email`
  )).rows;

  const investors = (await pool.query(
    `SELECT u.email, p.display_name, ip.preferred_domains
     FROM users u
     JOIN profiles p ON p.user_id = u.id
     LEFT JOIN investor_profiles ip ON ip.profile_id = p.id
     WHERE u.primary_role = 'INVESTOR'
     ORDER BY u.email`
  )).rows;

  const byDomain = {};
  for (const f of founders) {
    if (!f.startup) continue;
    const d = (f.domain || ['unclassified'])[0];
    (byDomain[d] ||= []).push(f);
  }

  const seeded = (e) => e.endsWith('@seed.test');
  const pw = (e) => (seeded(e) ? SEED_PASSWORD : 'whatever you set');

  let out = `# CapForge accounts

Generated by \`node scripts/write-credentials.js\` on ${new Date().toISOString().slice(0, 10)}.
Re-run it after any seeding: a list maintained by hand goes stale the first
time anything changes, and a demo run from a stale list fails in front of an
audience.

**Seeded accounts all use \`${SEED_PASSWORD}\`.** Accounts created by hand use
whatever password was set at the time.

${founders.filter(f => f.startup).length} ventures · ${contributors.length} contributors · ${investors.length} investors

---

## Founders

`;

  for (const [domain, list] of Object.entries(byDomain).sort()) {
    out += `### ${domain} (${list.length})\n\n`;
    out += `| Venture | Email | Founder | Stage | Readiness | Team | Open roles |\n`;
    out += `|---|---|---|---|---|---|---|\n`;
    for (const f of list) {
      out += `| **${f.startup}** | \`${f.email}\` | ${f.display_name} | ${f.stage || '—'} | ${f.readiness !== null ? Math.round(parseFloat(f.readiness)) : '—'} | ${f.team} | ${f.open_roles} |\n`;
    }
    out += `\n`;
  }

  const noVenture = founders.filter((f) => !f.startup);
  if (noVenture.length > 0) {
    out += `### Founders with no venture yet (${noVenture.length})\n\n`;
    for (const f of noVenture) out += `- \`${f.email}\` — ${f.display_name}\n`;
    out += `\n`;
  }

  out += `---\n\n## Contributors (${contributors.length})\n\n`;
  out += `| Email | Name | Headline | Fields |\n|---|---|---|---|\n`;
  for (const c of contributors) {
    out += `| \`${c.email}\` | ${c.display_name || '—'} | ${(c.headline || '—').slice(0, 52)} | ${(c.preferred_domains || []).slice(0, 3).join(', ') || '—'} |\n`;
  }

  out += `\n---\n\n## Investors (${investors.length})\n\n`;
  out += `| Email | Name | Invests in |\n|---|---|---|\n`;
  for (const i of investors) {
    out += `| \`${i.email}\` | ${i.display_name || '—'} | ${(i.preferred_domains || []).slice(0, 4).join(', ') || '—'} |\n`;
  }

  const handmade = [...founders, ...contributors, ...investors].filter((a) => a.email && !seeded(a.email));
  if (handmade.length > 0) {
    out += `\n---\n\n## Created by hand

These were signed up through the interface rather than seeded, so they are
the ones to use when showing that a stranger can arrive and be matched.

`;
    for (const a of handmade) out += `- \`${a.email}\` — ${a.display_name || '—'}\n`;
  }

  out += `\n---\n\n## Domain coverage

How many ventures a contributor sees when they choose each field. Anything on
one is a field where ranking has nothing to order.

| Field | Ventures |\n|---|---|\n`;
  for (const [d, l] of Object.entries(byDomain).sort((a, b) => b[1].length - a[1].length)) {
    out += `| ${d} | ${l.length} |\n`;
  }

  const file = path.join(__dirname, '..', 'SEED-ACCOUNTS.md');
  fs.writeFileSync(file, out, 'utf8');
  console.log(`Wrote SEED-ACCOUNTS.md`);
  console.log(`  ${founders.filter(f => f.startup).length} ventures, ${contributors.length} contributors, ${investors.length} investors`);
  console.log(`  ${handmade.length} account(s) created by hand`);
  await pool.end();
  process.exit(0);
})().catch((e) => { console.error('Failed:', e.message); process.exit(1); });
